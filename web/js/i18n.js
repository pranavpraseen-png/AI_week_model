export const isLanguage = (code) => LANGUAGES.some((l) => l.code === code);
export const direction = (code) => LANGUAGES.find((l) => l.code === code)?.dir ?? "ltr";

export async function loadLanguage(code) {
  if (!isLanguage(code)) return "en";
  if (!STRINGS[code]) {
    try {
      STRINGS[code] = (await import(`./lang/${code}.js`)).default;
    } catch {
      return "en"; // offline before it was ever loaded: fall back to English
    }
  }
  return code;
}

// The browser's preferred language, if we have it.
export function preferredLanguage(list = globalThis.navigator?.languages ?? []) {
  for (const tag of list) {
    const code = String(tag).toLowerCase().split("-")[0];
    if (isLanguage(code)) return code;
  }
  return "en";
}

export function t(lang, key, vars = {}) {
  const table = STRINGS[lang] ?? STRINGS.en;
  const template = table[key] ?? STRINGS.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ""));
}
